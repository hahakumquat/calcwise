let K512n: bigint[] | null = null;
const MASK64 = (BigInt(1) << BigInt(64)) - BigInt(1);

export function sha512Bytes(input: Uint8Array): string {
  if (!K512n) K512n = K512.map((h) => BigInt('0x' + h));
  const K = K512n;
  const m = pad(input, 128, 16, true);
  const H = [
    '6a09e667f3bcc908', 'bb67ae8584caa73b', '3c6ef372fe94f82b', 'a54ff53a5f1d36f1',
    '510e527fade682d1', '9b05688c2b3e6c1f', '1f83d9abfb41bd6b', '5be0cd19137e2179',
  ].map((h) => BigInt('0x' + h));
  const b8 = BigInt(8);
  const rot = (x: bigint, n: number) => ((x >> BigInt(n)) | (x << BigInt(64 - n))) & MASK64;
  const w = new Array<bigint>(80);
  for (let off = 0; off < m.length; off += 128) {
    for (let i = 0; i < 16; i++) {
      let v = BigInt(0);
      for (let j = 0; j < 8; j++) v = (v << b8) | BigInt(m[off + i * 8 + j]);
      w[i] = v;
    }
    for (let i = 16; i < 80; i++) {
      const s0 = rot(w[i - 15], 1) ^ rot(w[i - 15], 8) ^ (w[i - 15] >> BigInt(7));
      const s1 = rot(w[i - 2], 19) ^ rot(w[i - 2], 61) ^ (w[i - 2] >> BigInt(6));
      w[i] = (w[i - 16] + s0 + w[i - 7] + s1) & MASK64;
    }
    let [a, b, c, d, e, f, g, h] = H;
    for (let i = 0; i < 80; i++) {
      const S1 = rot(e, 14) ^ rot(e, 18) ^ rot(e, 41);
      const ch = (e & f) ^ (~e & MASK64 & g);
      const t1 = (h + S1 + ch + K[i] + w[i]) & MASK64;
      const S0 = rot(a, 28) ^ rot(a, 34) ^ rot(a, 39);
      const maj = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (S0 + maj) & MASK64;
      h = g; g = f; f = e; e = (d + t1) & MASK64; d = c; c = b; b = a; a = (t1 + t2) & MASK64;
    }
    const add = [a, b, c, d, e, f, g, h];
    for (let i = 0; i < 8; i++) H[i] = (H[i] + add[i]) & MASK64;
  }
  return H.map((x) => x.toString(16).padStart(16, '0')).join('');
}

